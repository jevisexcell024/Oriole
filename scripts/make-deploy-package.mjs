#!/usr/bin/env node
// Writes the package.json (and lock file) that ships INSIDE the cPanel deploy zip.
//
// The project's own package.json lists everything needed to *build* the app — React,
// Vite, Monaco, Tailwind, test tools… (50+ packages, ~350 folders, ~350 MB). The deployed
// server is a single pre-built bundle (dist-server/server.mjs) plus pre-built web files, and
// only needs the dozen or so packages it actually imports. Shipping the full list made
// "Run NPM Install" on the host download and unpack hundreds of unused packages — a big
// burst of processes, memory and disk/inode use that shared hosts cap (and a failed or
// half-finished install leaves the app broken). This script derives the real runtime list
// by scanning the server sources, so it cannot silently fall out of date.
//
// Usage: node scripts/make-deploy-package.mjs <output-dir> [--with-embedded-db]

import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = process.argv[2];
const withEmbeddedDb = process.argv.includes("--with-embedded-db");
if (!outDir) { console.error("Usage: node scripts/make-deploy-package.mjs <output-dir> [--with-embedded-db]"); process.exit(1); }

const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const known = { ...pkg.devDependencies, ...pkg.dependencies };

// Every bare-specifier import in the server + shared sources: static, dynamic, and re-exports.
const used = new Set();
const spec = /(?:from\s+|import\s*\(\s*)["']([^."'][^"']*)["']/g;
for (const dir of ["server", "shared"]) {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    if (!f.endsWith(".ts")) continue;
    const src = fs.readFileSync(path.join(root, dir, f), "utf8");
    for (const m of src.matchAll(spec)) {
      const name = m[1].startsWith("@") ? m[1].split("/").slice(0, 2).join("/") : m[1].split("/")[0];
      if (!name.startsWith("node:") && name in known) used.add(name);
    }
  }
}
// The embedded database is only for hosts with no PostgreSQL (production refuses to boot
// without DATABASE_URL unless ALLOW_EMBEDDED_DB is set), so it is opt-in here.
if (!withEmbeddedDb) used.delete("@electric-sql/pglite");

const dependencies = {};
for (const name of [...used].sort()) {
  const installed = path.join(root, "node_modules", name, "package.json");
  dependencies[name] = fs.existsSync(installed) ? JSON.parse(fs.readFileSync(installed, "utf8")).version : known[name];
}

const lean = {
  name: pkg.name,
  private: true,
  type: "module",
  version: pkg.version,
  description: "Runtime package list for the pre-built Oriole server (generated by scripts/make-deploy-package.mjs).",
  scripts: {
    start: "node --env-file-if-exists=.env dist-server/server.mjs",
    "start:bundle": "node --env-file-if-exists=.env dist-server/server.mjs",
  },
  ...(pkg.engines ? { engines: pkg.engines } : {}),
  dependencies,
};

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "package.json"), JSON.stringify(lean, null, 2) + "\n");
console.log(`Runtime packages (${Object.keys(dependencies).length}): ${Object.entries(dependencies).map(([n, v]) => `${n}@${v}`).join(", ")}`);

// A matching lock file so the host installs exactly these versions. Best effort: needs the
// npm registry; if it can't be reached the zip still works (npm resolves the pinned versions).
try {
  execSync("npm install --package-lock-only --ignore-scripts --no-audit --no-fund", { cwd: outDir, stdio: "pipe" });
  console.log("Lock file generated.");
} catch (e) {
  console.warn("WARNING: could not generate package-lock.json (" + String(e.message).split("\n")[0] + "). The zip will ship without one.");
}
